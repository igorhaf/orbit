function assertOwnedPath(directory, target) {
  const path = relative(realpathSync(directory), resolve(target));
  assert.ok(path === '' || (!path.startsWith('..') && !path.startsWith('/')), `fixture mutation outside ${directory}`);
}

async function isolatedPostgres(t) {
  assert.ok(existsSync(join(pgBin, 'initdb')), 'native PostgreSQL 16 is required; no DATABASE_URL fallback');
  const directory = mkdtempSync(join(tmpdir(), 'orbit-isolated-checkout-pg-'));
  const data = join(directory, 'database'), socket = join(directory, 'socket'), storage = join(directory, 'worktrees');
  mkdirSync(socket, { mode: 0o700 }); mkdirSync(storage, { mode: 0o700 });
  const saved = new Map();
  for (const key of Object.keys(process.env)) {
    if (key.startsWith('PG') || key.startsWith('CODEX') || key === 'DATABASE_URL' || key === 'HOME' || key.startsWith('ORBIT_ISOLATED') || key === 'ORBIT_WORKTREE_ROOT') {
      saved.set(key, process.env[key]); delete process.env[key];
    }
  }
  process.env.HOME = directory;
  process.env.CODEX_HOME = join(directory, 'codex-home-must-remain-absent');
  process.env.CODEX_BIN = join(directory, 'codex-must-never-run');
  process.env.ORBIT_ISOLATED_RUNS = '1'; process.env.ORBIT_WORKTREE_ROOT = storage;
  const env = { PATH: process.env.PATH || '/usr/bin:/bin', HOME: directory, LANG: 'C', LC_ALL: 'C', TZ: 'UTC' };
  const port = randomInt(20000, 60000);
  const pg = (command, args) => execFileSync(join(pgBin, command), args, { cwd: directory, env, stdio: 'pipe', encoding: 'utf8', timeout: 30000 });
  let pool;
  t.after(async () => {
    try {
      assert.equal(existsSync(process.env.CODEX_HOME), false, 'test must never prepare Codex HOME');
      if (pool) await pool.end();
    } finally {
      if (existsSync(join(data, 'postmaster.pid'))) pg('pg_ctl', ['-D', data, '-m', 'immediate', '-w', '-t', '20', 'stop']);
      const markerDirectory = `/tmp/orbit-write-coordination-${process.getuid()}`;
      for (const [owner, runId] of fixtureMarkers) {
        const path = join(markerDirectory, `${owner}.json`);
        if (!existsSync(path)) continue;
        const marker = JSON.parse(readFileSync(path, 'utf8'));
        assert.equal(marker.owner, owner); assert.equal(marker.runId, runId); assert.ok(fixtureRunIds.has(runId)); assert.ok(marker.roots.length);
        for (const resource of marker.roots) assertOwnedPath(directory, resource.path);
        // Native database and all test children have stopped. Remove only a marker
        // bound to a UUID generated by this test and roots in its owned fixture.
        rmSync(path);
      }
      for (const key of ['HOME', 'CODEX_HOME', 'CODEX_BIN', 'ORBIT_ISOLATED_RUNS', 'ORBIT_WORKTREE_ROOT']) delete process.env[key];
      for (const [key, value] of saved) process.env[key] = value;
      assertOwnedPath(directory, directory); rmSync(directory, { recursive: true, force: true });
    }
  });
  pg('initdb', ['-D', data, '-U', 'orbit_fixture', '-A', 'trust', '--encoding=UTF8', '--locale=C', '--no-instructions']);
  pg('pg_ctl', ['-D', data, '-l', join(directory, 'postgres.log'), '-w', '-t', '20', '-o', `-k ${quote(socket)} -p ${port} -c listen_addresses='' -c fsync=off`, 'start']);
  const database = { host: socket, port, user: 'orbit_fixture', database: 'postgres', password: 'synthetic-unused', ssl: false, connectionTimeoutMillis: 3000, options: '-c statement_timeout=5000' };
  const { Pool } = require('pg'); pool = new Pool({ ...database, max: 8 });
  const identity = (await pool.query("SELECT current_setting('data_directory') AS directory,current_setting('listen_addresses') AS listeners,inet_server_addr() AS address,current_user AS actor")).rows[0];
  assert.equal(realpathSync(identity.directory), realpathSync(data)); assert.equal(identity.listeners, ''); assert.equal(identity.address, null); assert.equal(identity.actor, 'orbit_fixture');
  // This DDL is executed only after proving that the connection belongs to our
  // temporary Unix-socket-only cluster; no runtime schema/config is loaded.
  await pool.query('CREATE TABLE card_ai_runs(id uuid PRIMARY KEY,card_id uuid NOT NULL)');
  await pool.query(readFileSync(join(root, 'packages/orbit-core/sql/migrations/159_isolated_checkouts.sql'), 'utf8'));
  const db = { pool, query: async (sql, parameters) => (await pool.query(sql, parameters)).rows };
  const gitEnv = { ...env, GIT_CONFIG_NOSYSTEM: '1', GIT_CONFIG_GLOBAL: '/dev/null', GIT_TERMINAL_PROMPT: '0', GIT_OPTIONAL_LOCKS: '0' };
  const git = (path, ...args) => {
    assertOwnedPath(directory, path);
    return execFileSync('git', ['-C', path, '-c', 'core.hooksPath=/dev/null', ...args], { env: gitEnv, encoding: 'utf8', stdio: 'pipe', timeout: 10000 });
  };
  const fixture = name => {
    const path = join(directory, name); mkdirSync(path, { mode: 0o700 });
    git(path, 'init', '--quiet');
    writeFileSync(join(path, 'shared.txt'), 'baseline\n'); writeFileSync(join(path, 'removed.txt'), 'remove me\n');
    writeFileSync(join(path, '.gitignore'), '.env\nnode_modules/\n');
    mkdirSync(join(path, 'src')); writeFileSync(join(path, 'src/example.txt'), 'source\n');
    git(path, 'add', '.'); git(path, '-c', 'user.name=Fixture', '-c', 'user.email=fixture@example.invalid', 'commit', '--quiet', '-m', 'synthetic baseline');
    return { id: randomUUID(), root: path, workspace_id: randomUUID() };
  };
  return { directory, storage, pool, db, database, git, fixture };
}

function runIdentity(project, request, queue = 'card_runs') {
  const identity = { queue, runId: randomUUID(), cardId: randomUUID(), cardRevision: 7, projectId: project.id, authorizedProjectRoot: project.root, workspaceId: project.workspace_id, request };
  fixtureRunIds.add(identity.runId); return identity;
}

function registerFixtureMarkerCleanup(t, directory, run, owner) {
  t.after(() => {
    const path = join(`/tmp/orbit-write-coordination-${process.getuid()}`, `${owner}.json`);
    if (!existsSync(path)) return;
    const marker = JSON.parse(readFileSync(path, 'utf8'));
    assert.equal(marker.owner, owner); assert.equal(marker.runId, run.runId);
    assert.ok(marker.roots.length);
    for (const resource of marker.roots) assertOwnedPath(directory, resource.path);
    // An exact fixture marker is removed only after all fixture workers are dead;
    // this is teardown, never the product recovery/discard mechanism.
    rmSync(path);
  });
}

async function crashWorker() {
  const config = JSON.parse(process.argv[3]);
  process.env.ORBIT_ISOLATED_RUNS = '1'; process.env.ORBIT_WORKTREE_ROOT = config.storage;
  const { withIsolatedCheckout } = loadCore();
  const { Pool } = require('pg'), pool = new Pool({ ...config.database, max: 2 });
  const db = { pool, query: async (sql, parameters) => (await pool.query(sql, parameters)).rows };
  try {
    await withIsolatedCheckout(db, config.identity, async (checkout, lease) => {
      await lease.assertActive(); writeFileSync(join(checkout.root, 'shared.txt'), 'preserve after abrupt death\n');
      process.send({ event: 'acquired', root: checkout.root, worktreeRoot: checkout.worktreeRoot, owner: lease.owner });
      await new Promise(() => {});
    });
  } catch (error) { process.send({ event: 'failed', message: String(error.message), code: error.code }); }
  finally { await pool.end(); process.disconnect(); }
}

