import 'reflect-metadata';
import 'dotenv/config';
import assert from 'node:assert/strict';
import {test} from 'node:test';
import {randomUUID} from 'node:crypto';
import {readFile} from 'node:fs/promises';
import {resolve} from 'node:path';
import {Pool} from 'pg';
import {Db} from './db';
import {FeaturesService} from './features';
import {CardExtensionsService} from './card-extensions';
import {cardContextsPrompt,linkedCardContexts} from './card-contexts';
import {migrateVersions} from './migrations';

test('checklist conversion links live context and manual references remain scoped to the board',async()=>{
  const db=new Db(),schema='contexts_test_'+randomUUID().replaceAll('-','');
  await db.query(`CREATE SCHEMA ${schema}`);
  await db.pool.end();
  db.pool=new Pool({connectionString:process.env.DATABASE_URL,options:`-c search_path=${schema},public`});
  try{
    await db.query(await readFile(resolve(__dirname,'../sql/schema.sql'),'utf8'));
    await db.query(await readFile(resolve(__dirname,'../sql/pre-022-compat.sql'),'utf8'));
    await migrateVersions(db.pool);
    await migrateVersions(db.pool);
    const user=(await db.one("INSERT INTO users(name,email,password_hash) VALUES('Context owner',$1,'x') RETURNING id",[randomUUID()+'@example.invalid']))!.id;
    const outsider=(await db.one("INSERT INTO users(name,email,password_hash) VALUES('Outsider',$1,'x') RETURNING id",[randomUUID()+'@example.invalid']))!.id;
    const board=(await db.one("INSERT INTO boards(title,owner_id) VALUES('Context board',$1) RETURNING id",[user]))!.id;
    const otherBoard=(await db.one("INSERT INTO boards(title,owner_id) VALUES('Other board',$1) RETURNING id",[user]))!.id;
    await db.query("INSERT INTO board_members(board_id,user_id,role) VALUES($1,$3,'owner'),($2,$3,'owner')",[board,otherBoard,user]);
    const list=(await db.one("INSERT INTO lists(board_id,title) VALUES($1,'Tasks') RETURNING id",[board]))!.id;
    const otherList=(await db.one("INSERT INTO lists(board_id,title) VALUES($1,'Other tasks') RETURNING id",[otherBoard]))!.id;
    const parent=(await db.one("INSERT INTO cards(list_id,title,description) VALUES($1,'Original purpose','Original description') RETURNING id",[list]))!.id;
    const reference=(await db.one("INSERT INTO cards(list_id,title,description) VALUES($1,'Second reference','Supporting details') RETURNING id",[list]))!.id;
    const foreign=(await db.one("INSERT INTO cards(list_id,title) VALUES($1,'Foreign card') RETURNING id",[otherList]))!.id;
    const service=new CardExtensionsService(db,new FeaturesService(db));
    await service.updateContexts(parent,user,{ids:[reference]});
    const group=await service.createChecklist(parent,user,{title:'Release tasks'});
    const [item]=await service.addItems(group.id,user,{text:'Implement task'});
    const converted=await service.convertItem(item.id,user,{});
    assert.equal(converted.title,'Implement task');
    assert.equal(converted.description,converted.title);
    assert.equal(await db.one('SELECT id FROM checklist_items WHERE id=$1',[item.id]),null);
    assert.deepEqual((await service.contexts(converted.id,user)).selected.map(row=>row.id),[parent,reference]);
    await assert.rejects(()=>service.convertItem(item.id,user,{}),/não encontrado|convertido/);
    const childChecklist=await service.createChecklist(converted.id,user,{title:'Checklist'});
    const [demand]=await service.addItems(childChecklist.id,user,{text:'Validate nested demand'});
    const nested=await service.convertItem(demand.id,user,{});
    assert.deepEqual((await service.contexts(nested.id,user)).selected.map(row=>row.id),[converted.id,parent,reference]);
    await db.query('INSERT INTO board_architecture_contracts(board_id,reference_board_id) VALUES($1,$2)',[board,otherBoard]);
    await assert.rejects(()=>service.createField(board,user,{name:'Invented status',type:'text'}),/quadro de referência/);
    await assert.rejects(()=>db.query("INSERT INTO custom_fields(board_id,name,type) VALUES($1,'Invented status','text')",[board]),/arquitetura/);
    const legacyDescription='Convertido do checklist “Release tasks” do cartão “Original purpose”.\n\nContexto do cartão de origem:\nOriginal description';
    const legacy=(await db.one('INSERT INTO cards(list_id,title,description) VALUES($1,$2,$3) RETURNING id',[list,'Legacy conversion',legacyDescription]))!.id;
    const editedDescription=legacyDescription+'\n\nPersonal instructions.';
    const edited=(await db.one('INSERT INTO cards(list_id,title,description) VALUES($1,$2,$3) RETURNING id',[list,'Edited conversion',editedDescription]))!.id;
    await db.query('INSERT INTO card_contexts(card_id,context_card_id) VALUES($1,$3),($2,$3)',[legacy,edited,parent]);
    await db.query(await readFile(resolve(__dirname,'../sql/migrations/057_clean_converted_card_descriptions.sql'),'utf8'));
    assert.equal((await db.one('SELECT description FROM cards WHERE id=$1',[legacy]))!.description,'');
    assert.equal((await db.one('SELECT description FROM cards WHERE id=$1',[edited]))!.description,editedDescription);
    assert.deepEqual((await service.contexts(legacy,user)).selected.map(row=>row.id),[parent]);
    await service.updateContexts(converted.id,user,{ids:[reference,parent,reference]});
    assert.deepEqual((await service.contexts(converted.id,user)).selected.map(row=>row.id),[reference,parent]);
    await assert.rejects(()=>service.updateContexts(converted.id,user,{ids:[foreign]}),/quadros?|quadro/);
    await assert.rejects(()=>service.updateContexts(converted.id,user,{ids:[converted.id]}),/próprio contexto/);
    await assert.rejects(()=>service.contexts(converted.id,outsider));
    assert.deepEqual((await service.contexts(converted.id,user)).selected.map(row=>row.id),[reference,parent]);
    await db.query("UPDATE cards SET description='Updated purpose' WHERE id=$1",[parent]);
    const prompt=cardContextsPrompt(await linkedCardContexts(db,converted.id,user));
    assert.match(prompt,/Supporting details/);
    assert.match(prompt,/Updated purpose/);
    await service.updateContexts(parent,user,{ids:[converted.id]});
    assert.equal((await linkedCardContexts(db,converted.id,user)).length,2);
    await db.query('UPDATE cards SET list_id=$2 WHERE id=$1',[reference,otherList]);
    assert.deepEqual((await linkedCardContexts(db,converted.id,user)).map(row=>row.id),[parent]);
    await db.query('UPDATE cards SET archived_at=now() WHERE id=$1',[parent]);
    assert.equal(cardContextsPrompt(await linkedCardContexts(db,converted.id,user)),'');
    await service.updateContexts(converted.id,user,{ids:[]});
    assert.equal((await db.one('SELECT count(*)::int AS n FROM card_contexts WHERE card_id=$1',[converted.id]))!.n,0);
  }finally{
    await db.query(`DROP SCHEMA ${schema} CASCADE`);
    await db.pool.end();
  }
});
